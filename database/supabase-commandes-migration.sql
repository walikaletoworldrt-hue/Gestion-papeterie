-- Bons de commande aux fournisseurs (version 1.5.0)
--
-- A executer une fois dans Supabase > SQL Editor AVANT d'installer la version 1.5.0 sur les PC
-- et avant la mise a jour du site web. Le script peut etre relance sans risque.
-- Il faut que supabase-credit-migration.sql et supabase-vente-en-gros-migration.sql aient deja ete executes.
--
-- purchase_orders      : un bon de commande (brouillon, envoyee, partielle, recue, annulee), sans aucun prix
-- purchase_order_items : les articles commandes ; quantity et quantity_received sont en lots (rames, boites...)
--                        quand pack_label est rempli, sinon en unites. product_id vide = article hors catalogue.
-- A la reception, chaque article recu devient un reapprovisionnement normal (lot BC-...-R1).

create table if not exists public.purchase_orders (
  id bigint generated by default as identity primary key,
  reference text not null,
  supplier text not null,
  status text not null default 'brouillon' check (status in ('brouillon', 'envoyee', 'partielle', 'recue', 'annulee')),
  note text,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  received_at timestamptz,
  receipts_count integer not null default 0,
  user_id bigint references public.users(id) on delete set null,
  uid uuid not null default gen_random_uuid(),
  modified_at timestamptz,
  server_updated_at timestamptz,
  sync_version bigint,
  origin_device text
);

create unique index if not exists purchase_orders_uid_key on public.purchase_orders(uid);
create unique index if not exists purchase_orders_reference_key on public.purchase_orders(reference);
create index if not exists purchase_orders_sync_version_idx on public.purchase_orders(sync_version);

create table if not exists public.purchase_order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.purchase_orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  item_name text not null,
  unit text not null default 'piece',
  pack_label text,
  pack_size integer,
  quantity numeric(12, 2) not null check (quantity > 0),
  quantity_received numeric(12, 2) not null default 0 check (quantity_received >= 0),
  note text,
  uid uuid not null default gen_random_uuid(),
  modified_at timestamptz,
  server_updated_at timestamptz,
  sync_version bigint,
  origin_device text
);

create unique index if not exists purchase_order_items_uid_key on public.purchase_order_items(uid);
create index if not exists purchase_order_items_sync_version_idx on public.purchase_order_items(sync_version);
create index if not exists purchase_order_items_order_id_idx on public.purchase_order_items(order_id);
create index if not exists purchase_order_items_product_id_idx on public.purchase_order_items(product_id);

-- Synchronisation ligne par ligne, comme les autres tables (voir supabase-row-sync-migration.sql).
drop trigger if exists row_sync_stamp on public.purchase_orders;
create trigger row_sync_stamp
before insert or update on public.purchase_orders
for each row execute function public.row_sync_stamp();

drop trigger if exists row_sync_tombstone on public.purchase_orders;
create trigger row_sync_tombstone
after delete on public.purchase_orders
for each row execute function public.row_sync_tombstone();

drop trigger if exists row_sync_stamp on public.purchase_order_items;
create trigger row_sync_stamp
before insert or update on public.purchase_order_items
for each row execute function public.row_sync_stamp();

drop trigger if exists row_sync_tombstone on public.purchase_order_items;
create trigger row_sync_tombstone
after delete on public.purchase_order_items
for each row execute function public.row_sync_tombstone();

alter table public.purchase_orders enable row level security;
alter table public.purchase_order_items enable row level security;

drop policy if exists purchase_orders_select_policy on public.purchase_orders;
create policy purchase_orders_select_policy on public.purchase_orders
for select
to authenticated
using (true);

drop policy if exists purchase_orders_write_policy on public.purchase_orders;
create policy purchase_orders_write_policy on public.purchase_orders
for all
to authenticated
using (true)
with check (true);

drop policy if exists purchase_order_items_select_policy on public.purchase_order_items;
create policy purchase_order_items_select_policy on public.purchase_order_items
for select
to authenticated
using (true);

drop policy if exists purchase_order_items_write_policy on public.purchase_order_items;
create policy purchase_order_items_write_policy on public.purchase_order_items
for all
to authenticated
using (true)
with check (true);

grant select, insert, update, delete on public.purchase_orders to authenticated;
grant select, insert, update, delete on public.purchase_order_items to authenticated;

-- Recharge le cache de l'API pour que les nouvelles tables soient visibles tout de suite.
notify pgrst, 'reload schema';
