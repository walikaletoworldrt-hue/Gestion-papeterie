-- Ventes a credit et suivi des dettes (version 1.3.0)
--
-- A executer une fois dans Supabase > SQL Editor AVANT d'installer la version 1.3.0 sur les PC
-- et avant la mise a jour du site web. Le script peut etre relance sans risque.
--
-- sales.amount_paid : acompte paye au moment de la vente (vide = vente payee entierement, comme avant)
-- sales.due_date    : date limite de paiement d'une vente a credit
-- debt_payments     : versements recus ensuite pour rembourser une dette

alter table public.sales add column if not exists amount_paid numeric(12, 2);
alter table public.sales add column if not exists due_date date;

create table if not exists public.debt_payments (
  id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales(id) on delete cascade,
  amount numeric(12, 2) not null check (amount > 0),
  paid_at timestamptz not null default now(),
  payment_method text not null default 'Especes',
  note text,
  user_id bigint references public.users(id) on delete set null,
  uid uuid not null default gen_random_uuid(),
  modified_at timestamptz,
  server_updated_at timestamptz,
  sync_version bigint,
  origin_device text
);

create unique index if not exists debt_payments_uid_key on public.debt_payments(uid);
create index if not exists debt_payments_sync_version_idx on public.debt_payments(sync_version);
create index if not exists debt_payments_sale_id_idx on public.debt_payments(sale_id);

-- Synchronisation ligne par ligne, comme les autres tables (voir supabase-row-sync-migration.sql).
drop trigger if exists row_sync_stamp on public.debt_payments;
create trigger row_sync_stamp
before insert or update on public.debt_payments
for each row execute function public.row_sync_stamp();

drop trigger if exists row_sync_tombstone on public.debt_payments;
create trigger row_sync_tombstone
after delete on public.debt_payments
for each row execute function public.row_sync_tombstone();

alter table public.debt_payments enable row level security;

drop policy if exists debt_payments_select_policy on public.debt_payments;
create policy debt_payments_select_policy on public.debt_payments
for select
to authenticated
using (true);

drop policy if exists debt_payments_write_policy on public.debt_payments;
create policy debt_payments_write_policy on public.debt_payments
for all
to authenticated
using (true)
with check (true);

grant select, insert, update, delete on public.debt_payments to authenticated;

-- Recharge le cache de l'API pour que les nouvelles colonnes soient visibles tout de suite.
notify pgrst, 'reload schema';
