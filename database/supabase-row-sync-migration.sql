-- Synchronisation ligne par ligne : fondations (etape 1)
--
-- A executer une fois dans Supabase > SQL Editor, apres les autres migrations.
-- Le script peut etre relance sans risque.
--
-- Chaque table synchronisee recoit :
--   uid               identifiant unique partage par tous les postes et le web
--   modified_at       heure de la derniere modification (regle "la derniere modification gagne")
--   server_updated_at heure a laquelle le serveur a recu la modification
--   sync_version      numero croissant attribue par le serveur, pour recuperer seulement les nouveautes
--   origin_device     poste qui a fait la modification (P1, P2... ou web)
-- Chaque suppression est notee dans sync_tombstones pour etre appliquee sur les autres postes.

create extension if not exists pgcrypto;

create sequence if not exists public.row_sync_version_seq;

create table if not exists public.sync_tombstones (
  id bigint generated by default as identity primary key,
  table_name text not null,
  uid uuid not null,
  deleted_at timestamptz not null default now(),
  sync_version bigint not null default nextval('public.row_sync_version_seq'),
  origin_device text,
  unique (table_name, uid)
);

create index if not exists sync_tombstones_sync_version_idx on public.sync_tombstones(sync_version);

-- Poste a l'origine de l'ecriture en cours. Le moteur de synchronisation desktop envoie
-- l'en-tete HTTP x-origin-device (P1, P2...) ; sans en-tete, l'ecriture vient du web.
create or replace function public.row_sync_origin_device()
returns text
language plpgsql
stable
as $$
declare
  header_value text;
begin
  begin
    header_value := nullif(current_setting('request.headers', true), '')::json ->> 'x-origin-device';
  exception when others then
    header_value := null;
  end;

  return coalesce(
    nullif(current_setting('app.origin_device', true), ''),
    nullif(header_value, ''),
    'web'
  );
end;
$$;

create or replace function public.row_sync_stamp()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' then
    new.modified_at := coalesce(new.modified_at, now());
  elsif new.modified_at is not distinct from old.modified_at then
    -- Ecriture qui ne precise pas son heure de modification (version web) : on prend l'heure du serveur.
    new.modified_at := now();
  elsif new.modified_at < old.modified_at then
    -- La derniere modification gagne : une modification plus ancienne que celle du cloud est ignoree.
    return null;
  end if;

  new.sync_version := nextval('public.row_sync_version_seq');
  new.server_updated_at := now();
  new.origin_device := public.row_sync_origin_device();
  return new;
end;
$$;

create or replace function public.row_sync_tombstone()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.sync_tombstones (table_name, uid, origin_device)
  values (tg_table_name, old.uid, public.row_sync_origin_device())
  on conflict (table_name, uid) do update
    set deleted_at = now(),
        sync_version = nextval('public.row_sync_version_seq'),
        origin_device = excluded.origin_device;
  return old;
end;
$$;

do $$
declare
  t text;
begin
  foreach t in array array[
    'users',
    'clients',
    'expenses',
    'products',
    'services',
    'cybercafe_tariffs',
    'cybercafe_sales',
    'mikhmon_sales',
    'inventory_cycles',
    'initial_stocks',
    'replenishments',
    'sales',
    'sale_items',
    'sale_service_items',
    'stock_movements',
    'audit_logs'
  ]
  loop
    execute format('alter table public.%I add column if not exists uid uuid not null default gen_random_uuid()', t);
    execute format('alter table public.%I add column if not exists modified_at timestamptz', t);
    execute format('alter table public.%I add column if not exists server_updated_at timestamptz', t);
    execute format('alter table public.%I add column if not exists sync_version bigint', t);
    execute format('alter table public.%I add column if not exists origin_device text', t);

    execute format(
      'update public.%I set modified_at = coalesce(modified_at, now()), server_updated_at = coalesce(server_updated_at, now()), sync_version = coalesce(sync_version, nextval(''public.row_sync_version_seq'')) where sync_version is null or modified_at is null or server_updated_at is null',
      t
    );

    execute format('create unique index if not exists %I on public.%I(uid)', t || '_uid_key', t);
    execute format('create index if not exists %I on public.%I(sync_version)', t || '_sync_version_idx', t);

    execute format('drop trigger if exists row_sync_stamp on public.%I', t);
    execute format(
      'create trigger row_sync_stamp before insert or update on public.%I for each row execute function public.row_sync_stamp()',
      t
    );

    execute format('drop trigger if exists row_sync_tombstone on public.%I', t);
    execute format(
      'create trigger row_sync_tombstone after delete on public.%I for each row execute function public.row_sync_tombstone()',
      t
    );
  end loop;
end;
$$;

-- Heure du serveur : permet a chaque poste de corriger le decalage de son horloge.
create or replace function public.row_sync_server_time()
returns timestamptz
language sql
stable
as $$
  select now();
$$;

alter table public.sync_tombstones enable row level security;

drop policy if exists sync_tombstones_select_policy on public.sync_tombstones;
create policy sync_tombstones_select_policy on public.sync_tombstones
for select
to authenticated
using (true);

grant select on public.sync_tombstones to authenticated;
grant usage on sequence public.row_sync_version_seq to authenticated;
grant execute on function public.row_sync_origin_device() to authenticated;
grant execute on function public.row_sync_server_time() to authenticated;

-- Etape 2 : numero de facture web (serie W), attribue par le serveur en une seule operation
-- pour que deux navigateurs ne recoivent jamais le meme numero.
-- Format : Fact-SA26-W-0001 (les PC utilisent P1, P2...).
create or replace function public.invoice_series_label(series_index integer)
returns text
language plpgsql
immutable
as $$
declare
  idx integer := series_index;
  label text := '';
begin
  loop
    label := chr(65 + (idx % 26)) || label;
    idx := (idx / 26) - 1;
    exit when idx < 0;
  end loop;
  return label;
end;
$$;

create or replace function public.next_web_invoice_reference()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  current_year_value integer := extract(year from now())::integer;
  seq record;
begin
  if auth.uid() is null then
    raise exception 'Connexion requise pour creer une facture.';
  end if;

  insert into public.invoice_sequences (id, current_year, series_index, next_number)
  values (1, current_year_value, 0, 1)
  on conflict (id) do nothing;

  -- Les expressions du SET lisent les anciennes valeurs : le numero attribue est l'ancien next_number.
  update public.invoice_sequences
  set series_index = case when current_year = current_year_value then series_index else 0 end,
      next_number = case when current_year = current_year_value then next_number + 1 else 2 end,
      current_year = current_year_value,
      updated_at = now()
  where id = 1
  returning current_year, series_index, next_number - 1 as issued_number
  into seq;

  return 'Fact-S' || public.invoice_series_label(seq.series_index) || right(seq.current_year::text, 2)
    || '-W-' || lpad(seq.issued_number::text, 4, '0');
end;
$$;

grant execute on function public.invoice_series_label(integer) to authenticated;
grant execute on function public.next_web_invoice_reference() to authenticated;

-- Etape 3 : registre des postes. Un code poste (P1, P2...) ne peut appartenir qu'a un seul PC,
-- sinon deux PC produiraient les memes numeros de facture.
create table if not exists public.sync_devices (
  code text primary key,
  device_id uuid not null,
  device_label text not null,
  claimed_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

alter table public.sync_devices enable row level security;

drop policy if exists sync_devices_select_policy on public.sync_devices;
create policy sync_devices_select_policy on public.sync_devices
for select
to authenticated
using (true);

grant select on public.sync_devices to authenticated;

-- Reserve le code pour ce PC. Un PC reinstalle garde son nom Windows : il peut reprendre son code.
create or replace function public.row_sync_claim_device(p_code text, p_device_id uuid, p_device_label text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  existing public.sync_devices;
begin
  if auth.uid() is null then
    raise exception 'Connexion requise pour synchroniser.';
  end if;

  select * into existing from public.sync_devices where code = p_code for update;

  if existing.code is null then
    insert into public.sync_devices (code, device_id, device_label) values (p_code, p_device_id, p_device_label);
  elsif existing.device_id = p_device_id or existing.device_label = p_device_label then
    update public.sync_devices
    set device_id = p_device_id, device_label = p_device_label, last_seen_at = now()
    where code = p_code;
  else
    raise exception 'Le code poste % est deja utilise par le PC "%". Choisissez un autre code pour ce poste.', p_code, existing.device_label;
  end if;
end;
$$;

-- Correspondance id cloud <-> nom d'utilisateur, sans donnee sensible, pour traduire les references aux utilisateurs.
create or replace function public.row_sync_user_directory()
returns table (id bigint, username text)
language sql
stable
security definer
set search_path = public
as $$
  select u.id, u.username from public.users u where auth.uid() is not null;
$$;

grant execute on function public.row_sync_claim_device(text, uuid, text) to authenticated;
grant execute on function public.row_sync_user_directory() to authenticated;

-- Etape 4 : cycle d'inventaire en cours = le plus recemment demarre.
-- Les numeros internes (id) ne suivent plus l'ordre des cycles quand plusieurs postes en creent.
create or replace function public.current_inventory_cycle_id()
returns bigint
language sql
stable
as $$
  select ic.id from public.inventory_cycles ic order by ic.started_at desc, ic.id desc limit 1;
$$;

grant execute on function public.current_inventory_cycle_id() to authenticated;

create or replace view public.current_stock_view as
select
  p.id as product_id,
  p.name as product_name,
  coalesce(sum(case when sm.quantity > 0 then sm.quantity else 0 end), 0) as quantity_in,
  coalesce(sum(case when sm.quantity < 0 then abs(sm.quantity) else 0 end), 0) as quantity_out,
  coalesce(sum(sm.quantity), 0) as current_stock,
  p.alert_threshold as alert_threshold
from public.products p
left join public.stock_movements sm
  on sm.product_id = p.id
 and sm.cycle_id = coalesce(public.current_inventory_cycle_id(), 1)
group by p.id, p.name, p.alert_threshold;
